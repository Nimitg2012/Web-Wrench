import { Copy, LoaderCircle, RefreshCw, Sparkles, X } from '../ui/icons.tsx'
import { useEffect, useState } from 'react'
import { useLocation } from 'react-router-dom'
import { demoAssistantReply } from '../../data/demoData.ts'
import { useApp } from '../../context/context.ts'
import { requestChat, requestExplanation } from '../../services/aiService.ts'
import type { Explanation } from '../../types/index.ts'
import { Button } from '../ui/Button.tsx'
import { Drawer } from '../ui/Drawer.tsx'
import { controlClass } from '../ui/Overlay.tsx'

export function ExplainDrawer() {
  const { explain, closeExplain, mode, toast } = useApp()
  const { pathname } = useLocation()
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [live, setLive] = useState<Explanation | null>(null)
  const [showTechnical, setShowTechnical] = useState(mode === 'advanced')
  const [question, setQuestion] = useState('')
  const [followUps, setFollowUps] = useState<Array<{ question: string; answer: string }>>([])
  const [followError, setFollowError] = useState<string | null>(null)
  const [followLoading, setFollowLoading] = useState(false)
  const [attempt, setAttempt] = useState(0)

  useEffect(() => {
    closeExplain()
  }, [pathname])

  useEffect(() => {
    if (!explain || explain.source === 'demo') {
      setLive(null)
      setError(null)
      setLoading(false)
      return
    }
    let cancelled = false
    setLoading(true)
    setError(null)
    setLive(null)
    void requestExplanation(explain, mode === 'beginner')
      .then((result) => {
        if (!cancelled) setLive(result)
      })
      .catch((reason: unknown) => {
        if (!cancelled) setError(reason instanceof Error ? reason.message : 'The AI explanation could not be completed.')
      })
      .finally(() => {
        if (!cancelled) setLoading(false)
      })
    return () => {
      cancelled = true
    }
  }, [explain, mode, attempt])

  useEffect(() => {
    setShowTechnical(mode === 'advanced')
    setFollowUps([])
    setQuestion('')
    setFollowError(null)
  }, [explain, mode])

  if (!explain) return null
  const explanation = explain.source === 'demo' ? explain.demoExplanation : live

  const copy = async () => {
    const parts = [
      explain.title,
      explain.source === 'demo' ? 'Simulated tutorial explanation.' : 'AI explanation.',
      explanation?.whatHappened ?? '',
      ...(explanation?.why ?? []),
      explanation?.seriousness ?? '',
      ...(explanation?.nextSteps ?? []),
    ]
    try {
      await navigator.clipboard.writeText(parts.filter(Boolean).join('\n'))
      toast('Explanation copied.', 'success')
    } catch {
      toast('Copying is not available in this browser.', 'error')
    }
  }

  const ask = async () => {
    const trimmed = question.trim()
    if (!trimmed || followLoading) return
    setQuestion('')
    if (explain.source === 'demo') {
      setFollowUps((current) => [...current, { question: trimmed, answer: demoAssistantReply(trimmed, explain.title) }])
      return
    }
    setFollowLoading(true)
    setFollowError(null)
    try {
      const reply = await requestChat(
        [{ id: 'follow', role: 'user', content: trimmed, demo: false }],
        `${explain.title}\n${explain.monitoringResult}\n${explain.observed}`,
        mode === 'beginner',
      )
      setFollowUps((current) => [...current, { question: trimmed, answer: reply }])
    } catch (reason) {
      setFollowError(reason instanceof Error ? reason.message : 'The follow-up could not be answered.')
    } finally {
      setFollowLoading(false)
    }
  }

  return (
    <Drawer open title="Explain with AI" onClose={closeExplain}>
      <div className="flex items-start justify-between gap-3 border-b border-line px-5 py-4">
        <div>
          <p className="flex items-center gap-2 text-xs font-semibold uppercase tracking-[0.14em] text-purple">
            <Sparkles className="h-3.5 w-3.5" />
            Explain with AI
          </p>
          <h2 className="mt-1 text-lg font-semibold break-words">{explain.title}</h2>
        </div>
        <button type="button" aria-label="Close panel" onClick={closeExplain} className="grid h-11 w-11 shrink-0 place-items-center rounded-lg border border-line md:h-9 md:w-9">
          <X className="h-4 w-4" />
        </button>
      </div>
      <div className="flex-1 space-y-4 overflow-y-auto px-5 py-4">
        {explain.source === 'demo' ? (
          <p className="rounded-xl border border-purple/30 bg-purple/10 px-3 py-2 text-sm text-ink">
            Simulated explanation for the tutorial. This was not generated by a live model.
          </p>
        ) : (
          <p className="rounded-xl border border-line bg-panel px-3 py-2 text-sm text-muted">
            The assistant only knows the facts below. It cannot see a live website unless monitoring is connected.
          </p>
        )}
        <section className="rounded-xl border border-line bg-panel p-3">
          <h3 className="text-sm font-semibold">What we recorded</h3>
          <dl className="mt-2 space-y-2 text-sm">
            <div>
              <dt className="text-xs text-muted">Observed</dt>
              <dd>{explain.observed}</dd>
            </div>
            <div>
              <dt className="text-xs text-muted">Expected</dt>
              <dd>{explain.expected}</dd>
            </div>
            <div>
              <dt className="text-xs text-muted">Monitoring result</dt>
              <dd>{explain.monitoringResult}</dd>
            </div>
          </dl>
        </section>
        {loading ? (
          <div className="flex items-center gap-2 text-sm text-muted">
            <LoaderCircle className="h-4 w-4 animate-spin" />
            Asking the AI service…
          </div>
        ) : null}
        {error ? (
          <div className="rounded-xl border border-danger/40 bg-danger/10 p-3 text-sm">
            <p>{error}</p>
            <Button className="mt-3" size="sm" variant="secondary" onClick={() => setAttempt((value) => value + 1)}>
              <RefreshCw className="h-3.5 w-3.5" />
              Retry
            </Button>
          </div>
        ) : null}
        {explanation ? (
          <div className="space-y-4 text-sm leading-6">
            <Block title="What happened" body={explanation.whatHappened} />
            <ListBlock title="Why it might have happened" items={explanation.why} />
            <Block title="How serious it is" body={explanation.seriousness} />
            <ListBlock title="Recommended next steps" items={explanation.nextSteps} />
            {showTechnical ? (
              <ListBlock title="Technical details" items={explanation.technical.length > 0 ? explanation.technical : [explain.technical || 'No technical details were recorded.']} />
            ) : null}
          </div>
        ) : null}
        <div className="space-y-2">
          {followUps.map((item) => (
            <div key={item.question} className="rounded-xl border border-line bg-midnight p-3 text-sm">
              <p className="text-muted">You asked</p>
              <p>{item.question}</p>
              <p className="mt-2 text-muted">{explain.source === 'demo' ? 'Simulated reply' : 'Assistant'}</p>
              <p>{item.answer}</p>
            </div>
          ))}
          {followError ? <p className="text-sm text-danger">{followError}</p> : null}
          <div className="flex min-w-0 gap-2">
            <input
              className={`${controlClass} min-w-0 flex-1`}
              value={question}
              placeholder="Ask a follow-up question"
              onChange={(event) => setQuestion(event.target.value)}
              onKeyDown={(event) => {
                if (event.key === 'Enter') void ask()
              }}
            />
            <Button variant="ai" onClick={() => void ask()} disabled={followLoading || !question.trim()}>
              Ask
            </Button>
          </div>
        </div>
      </div>
      <div className="flex flex-wrap gap-2 border-t border-line px-5 py-4">
        <Button size="sm" variant="secondary" onClick={() => void copy()} disabled={!explanation}>
          <Copy className="h-3.5 w-3.5" />
          Copy explanation
        </Button>
        <Button size="sm" variant="ghost" onClick={() => setShowTechnical((open) => !open)}>
          {showTechnical ? 'Hide technical details' : 'View technical details'}
        </Button>
        <Button size="sm" variant="ghost" onClick={closeExplain}>
          Close panel
        </Button>
      </div>
    </Drawer>
  )
}

function Block({ title, body }: { title: string; body: string }) {
  return (
    <section>
      <h3 className="font-semibold text-ink">{title}</h3>
      <p className="text-muted">{body}</p>
    </section>
  )
}

function ListBlock({ title, items }: { title: string; items: string[] }) {
  if (items.length === 0) return null
  return (
    <section>
      <h3 className="font-semibold text-ink">{title}</h3>
      <ul className="mt-1 list-disc space-y-1 pl-4 text-muted">
        {items.map((item) => (
          <li key={item}>{item}</li>
        ))}
      </ul>
    </section>
  )
}
